"""Tool registry and the analysis tools the model can call."""

import json
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any, Literal, Self

from pydantic import BaseModel, Field, ValidationError, model_validator

from ga4_agent.sql import QueryError, QueryParams, QueryResult, SqlRunner


@dataclass
class TurnContext:
    """State shared by the tool calls of one turn: the query results they produced."""

    results: dict[str, QueryResult] = field(default_factory=dict)

    def store(self, result: QueryResult) -> str:
        result_id = f"r{len(self.results) + 1}"
        self.results[result_id] = result
        return result_id


@dataclass(frozen=True)
class ToolOutput:
    content: str  # what the model reads
    display: dict[str, Any]  # what the UI renders
    is_error: bool = False


@dataclass(frozen=True)
class Tool:
    name: str
    description: str
    input_model: type[BaseModel]
    handler: Callable[[Any, TurnContext], ToolOutput]  # receives a validated input_model instance


class ToolRegistry:
    def __init__(self, tools: list[Tool]) -> None:
        self._tools = {tool.name: tool for tool in tools}

    def definitions(self) -> list[dict]:
        return [
            {"name": t.name, "description": t.description, "input_schema": t.input_model.model_json_schema()}
            for t in self._tools.values()
        ]

    def run(self, name: str, raw_input: dict, ctx: TurnContext) -> ToolOutput:
        tool = self._tools.get(name)
        if tool is None:
            return _error(f"Unknown tool {name!r}.")
        try:
            args = tool.input_model.model_validate(raw_input)
        except ValidationError as error:
            return _error(f"Invalid input for {name}: {error}")
        return tool.handler(args, ctx)


def _error(message: str, display: dict[str, Any] | None = None) -> ToolOutput:
    return ToolOutput(content=message, display=display or {"error": message}, is_error=True)


class RunSqlInput(BaseModel):
    sql: str = Field(description="One BigQuery Standard SQL SELECT statement, starting from the building blocks.")
    purpose: str = Field(
        max_length=80,
        description="What the query computes, in a few plain words shown to the user, e.g. 'Revenue by month'.",
    )


def run_sql_tool(runner: SqlRunner, *, preview_rows: int) -> Tool:
    def handler(args: RunSqlInput, ctx: TurnContext) -> ToolOutput:
        try:
            result = runner.run(args.sql)
        except QueryError as error:
            return _error(str(error), display={"label": args.purpose, "sql": args.sql, "error": str(error)})

        return _query_output(args.purpose, args.sql, result, ctx, preview_rows)

    return Tool(
        name="run_sql",
        description=(
            "Run a read-only SQL query against the dataset and get back a result_id, the columns, "
            "the total row count and a preview of the rows. Errors come back as messages you can "
            "fix and retry."
        ),
        input_model=RunSqlInput,
        handler=handler,
    )


def compiled_query_tool(
    runner: SqlRunner,
    *,
    name: str,
    description: str,
    input_model: type[BaseModel],
    compile: Callable[[Any], tuple[str, QueryParams]],
    label: Callable[[Any], str],
    preview_rows: int,
) -> Tool:
    """A tool whose SQL is generated by code from validated input, such as a metrics layer.

    Its results look exactly like run_sql results, so charts and the UI treat them the same way.
    """

    def handler(args: BaseModel, ctx: TurnContext) -> ToolOutput:
        sql, params = compile(args)
        shown = "".join(f"-- @{key} = {value}\n" for key, value in params.items()) + sql
        try:
            result = runner.run(sql, params)
        except QueryError as error:
            return _error(str(error), display={"label": label(args), "sql": shown, "error": str(error)})
        return _query_output(label(args), shown, result, ctx, preview_rows)

    return Tool(name=name, description=description, input_model=input_model, handler=handler)


def _query_output(label: str, sql: str, result: QueryResult, ctx: TurnContext, preview_rows: int) -> ToolOutput:
    result_id = ctx.store(result)
    preview = result.rows[:preview_rows]
    columns = [{"name": c.name, "type": c.type} for c in result.columns]
    sent = {
        "result_id": result_id,
        "columns": columns,
        "total_rows": result.total_rows,
        "rows": preview,
        "note": f"Showing the first {len(preview)} of {result.total_rows} rows.",
    }
    display = {
        "label": label,
        "sql": sql,
        "result_id": result_id,
        "columns": columns,
        "rows": preview,
        "total_rows": result.total_rows,
    }
    return ToolOutput(content=json.dumps(sent), display=display)


NUMERIC_TYPES = {"INTEGER", "INT64", "FLOAT", "FLOAT64", "NUMERIC", "BIGNUMERIC"}


class CreateChartInput(BaseModel):
    result_id: str = Field(description="A result_id returned by a query earlier in this answer.")
    type: Literal["line", "bar", "funnel", "pie"] = Field(
        description="line for trends over time, bar to compare categories, funnel for step drop-off, pie for shares."
    )
    title: str = Field(description="Short title in plain business language.")
    x: str = Field(description="Column with the labels: dates, categories or funnel steps, one row each.")
    y: list[str] = Field(
        min_length=1, max_length=3, description="Numeric columns to plot; exactly one for funnel and pie."
    )

    @model_validator(mode="after")
    def single_series_for_funnel_and_pie(self) -> Self:
        if self.type in ("funnel", "pie") and len(self.y) != 1:
            raise ValueError(f"a {self.type} chart takes exactly one y column")
        return self


def create_chart_tool() -> Tool:
    def handler(args: CreateChartInput, ctx: TurnContext) -> ToolOutput:
        result = ctx.results.get(args.result_id)
        if result is None:
            return _error(f"Unknown result_id {args.result_id!r}; available: {', '.join(ctx.results) or 'none'}.")

        types = {c.name: c.type for c in result.columns}
        missing = [name for name in [args.x, *args.y] if name not in types]
        if missing:
            return _error(f"Unknown columns {missing}; the result has {list(types)}.")
        not_numeric = [name for name in args.y if types[name] not in NUMERIC_TYPES]
        if not_numeric:
            return _error(f"y columns must be numeric; {not_numeric} are not.")

        # The rows come from the stored result, so every number on the chart comes from the query.
        rows = [{name: row[name] for name in [args.x, *args.y]} for row in result.rows]
        display = {"type": args.type, "title": args.title, "x": args.x, "y": args.y, "rows": rows}
        return ToolOutput(content=f"Chart shown to the user with {len(rows)} data points.", display=display)

    return Tool(
        name="create_chart",
        description=(
            "Show the user a chart of a query result from this answer. The chart uses the full stored "
            "result, not the preview. Shape the query so each row is one point, bar, slice or funnel step."
        ),
        input_model=CreateChartInput,
        handler=handler,
    )
